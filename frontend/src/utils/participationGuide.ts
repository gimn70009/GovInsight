import type { ParticipationGuide, ParticipationReviewReason, ParticipationRule } from '../api/types'

export const participationSections = [
  { key: 'BASIC', title: '기본 신청 자격', note: '신청 대상과 충족해야 하는 기준' },
  { key: 'TARGETED', title: '특정 기업에 적용되는 제한', note: '해당하는 대상만 확인하세요' },
  { key: 'EXCLUSION', title: '신청 제외 사유', note: '제외 기준과 예외를 함께 확인하세요' },
  { key: 'FUNDING', title: '자부담·사업비', note: '지원금에 따른 비용 부담과 사용 기준' },
  { key: 'PREFERENCE', title: '우대·가점', note: '신청 자격과 별도로 적용되는 우대 기준' },
  { key: 'DEDUCTION', title: '감점 기준', note: '신청 제외와는 별도로 평가 점수에서 차감되는 기준' },
  { key: 'REVIEW', title: '원문 확인이 필요한 조건', note: '아래 조건은 적용 대상이나 기준을 원문에서 확인해 주세요.' },
] as const

// These are presentation messages generated by the server, not notice conditions.
const reviewMessages = new Set([
  '표에서 적용 대상별 자격 요건을 구분하지 못했습니다.',
  '자격 조건의 문장이 끝까지 확인되지 않아 원문 확인이 필요합니다.',
  '원문에서 같은 대상·유형의 신청 기준이 서로 다르게 확인됩니다.',
  '적용 대상이나 기준을 확정하지 못한 항목입니다. 원문에서 해당 조건을 확인해 주세요.',
])

function reviewContent(item: ParticipationRule): PresentedParticipationRule {
  const review = explainParticipationReview(item)
  const details = item.details.filter(text => !reviewMessages.has(text.trim()))
  const guidance = item.guidance.filter(text => !reviewMessages.has(text.trim()))
  if (!reviewMessages.has(item.text.trim())) return { ...item, details, guidance, review }
  // Incomplete sentences retain their original wording in details. Tables and
  // conflicting criteria retain the original excerpts without inferring cell relationships.
  const original = item.text.trim().startsWith('자격 조건의 문장이') ? details.shift() : undefined
  const excerpts = [...new Set(item.sources.map(source => source?.excerpt?.trim())
    .filter((text): text is string => !!text && !reviewMessages.has(text)))]
  return { ...item, text: original || excerpts.join('\n\n'), details, guidance, review }
}

export type ParticipationDomain = 'eligibility' | 'funding' | 'evaluation'

function ruleDomain(rule: ParticipationRule): ParticipationDomain {
  if (rule.section === 'FUNDING' || (rule.section === 'REVIEW' && rule.label === '자부담·사업비')) return 'funding'
  if (rule.section === 'PREFERENCE' || rule.section === 'DEDUCTION'
    || (rule.section === 'REVIEW' && (/^평가 (?:가점|감점)$/u.test(rule.label)
      || rule.reviewReason === 'PREFERENCE_NEGATED'
      || (rule.sources.length > 0 && rule.sources.every(source => /^(?:우대|(?:공통\s*)?가점|(?:공통\s*)?감점|평가 기준)/u.test(source.sectionTitle?.trim() ?? '')))))) return 'evaluation'
  return 'eligibility'
}

export function groupParticipationRules(guide?: ParticipationGuide, domain?: ParticipationDomain) {
  // Compatibility for saved responses produced before presentation rules were added.
  const rules: ParticipationRule[] = guide?.rules ?? (guide?.conditions ?? []).map(item => ({
    section: ({ MANDATORY: 'BASIC', FUNDING: 'FUNDING', PREFERENCE: 'PREFERENCE', DEDUCTION: 'DEDUCTION', EXCLUSION: 'EXCLUSION', REVIEW_REQUIRED: 'REVIEW' } as const)[item.kind] ?? 'REVIEW',
    reviewReason: item.reviewReason, label: item.category, text: item.text, scope: item.scope, audience: null,
    details: item.details ?? [], exceptions: [], guidance: [], outcomes: [], sources: [item.source],
  }))
  return participationSections.map(section => {
    const groups: { scope: string | null; labels: { label: string; rules: PresentedParticipationRule[] }[] }[] = []
    for (const rule of rules) {
      if (domain && ruleDomain(rule) !== domain) continue;
      const knownSection = participationSections.some(value => value.key === rule.section) ? rule.section : 'REVIEW'
      if (knownSection !== section.key || !rule.text?.trim() || !rule.sources?.some(source => source?.excerpt?.trim())) continue
      const item = knownSection === 'REVIEW' ? reviewContent(rule) : rule
      if (!item.text.trim()) continue
      const scope = item.scope?.trim() || null
      let group = groups.find(value => value.scope === scope)
      if (!group) { group = { scope, labels: [] }; groups.push(group) }
      const label = item.label?.trim() || '참여 자격'
      let labeled = group.labels.find(value => value.label === label)
      if (!labeled) { labeled = { label, rules: [] }; group.labels.push(labeled) }
      labeled.rules.push(knownSection === item.section ? item : { ...item, section: 'REVIEW' })
    }
    return { ...section, groups }
  }).filter(section => section.groups.length > 0)
}


/** Render only explicitly supplied type outcomes; do not infer other types or final eligibility. */
export function applicationTypeSentence(item: ParticipationRule, variants: ParticipationGuide['variants'] = []): string | null {
  if (item.section !== 'TARGETED' || item.outcomes.length === 0) return null
  const allowed = [...new Set(item.outcomes.filter(outcome => outcome.status === 'ELIGIBLE').map(outcome => outcome.variant))]
  const denied = [...new Set(item.outcomes.filter(outcome => outcome.status === 'INELIGIBLE').map(outcome => outcome.variant))]
  if (allowed.some(name => denied.includes(name)) || allowed.length + denied.length === 0) return null
  const nameWithMeaning = (name: string) => {
    const descriptions = [...new Set(variants.filter(variant => variant.name === name)
      .map(variant => variant.description.trim()).filter(Boolean))]
    return descriptions.length === 1 ? `${name}(${descriptions[0]})` : name
  }
  const audience = item.audience?.trim() ?? ''
  const last = audience.charCodeAt(audience.length - 1)
  const particle = last >= 0xac00 && last <= 0xd7a3 ? ((last - 0xac00) % 28 === 0 ? '는' : '은') : '의 경우,'
  const subject = audience ? `${audience}${particle} ` : ''
  const exclusive = /(?:에\s*한해|에만)\s*신청/u.test(item.text)
  const permitted = `${allowed.map(nameWithMeaning).join(', ')}에${exclusive ? '만' : ''} 신청할 수`
  const prohibited = `${denied.map(nameWithMeaning).join(', ')}에는 신청할 수 없습니다.`
  if (allowed.length && denied.length) return `${subject}${permitted} 있으며, ${prohibited}`
  return allowed.length ? `${subject}${permitted} 있습니다.` : subject + prohibited
}

export type PresentedParticipationRule = ParticipationRule & { review?: { title: string; reason: string } }

const legacyReasons: Record<string, ParticipationReviewReason> = {
  '표에서 적용 대상별 자격 요건을 구분하지 못했습니다.': 'TABLE_MAPPING_UNCLEAR',
  '자격 조건의 문장이 끝까지 확인되지 않아 원문 확인이 필요합니다.': 'INCOMPLETE_TEXT',
  '원문에서 같은 대상·유형의 신청 기준이 서로 다르게 확인됩니다.': 'CONFLICTING_CRITERIA',
}

function topic(item: ParticipationRule) {
  // Keywords identify what to check, never why it failed. Failure reasons come
  // from the resolver; the full original remains exclusively in the evidence panel.
  const text = [legacyReasons[item.text.trim()] ? '' : item.text, ...item.details].join(' ')
  if (/전담\s*인력|전담\s*인원/.test(text)) return {
    title: /경력/.test(text) ? '전담인력·경력 요건' : '전담인력 구성 요건',
    check: /경력/.test(text) ? '직급별 인원수와 경력 기준이 누구에게 적용되는지 확인해 주세요.' : '필요한 인원수와 전담·겸직 구분의 적용 대상을 확인해 주세요.',
    context: '전담인력 문구가 신청 자격에 해당하는지 연결된 문맥이 확인되지 않았습니다. ' + (/경력/.test(text) ? '직급별 인원수와 경력 기준의 적용 대상을 확인해 주세요.' : '필요한 인원수와 전담·겸직 구분의 적용 대상을 확인해 주세요.'),
  }
  if (/전문가단|전문가/.test(text)) return {
    title: '전문가단 구성·운영 요건',
    check: '전문가단의 규모와 역할이 신청 자격인지 선정 후 운영 요건인지 확인해 주세요.',
    context: '전문가단의 구성·운영 문구만 확인되어 신청 시 갖춰야 하는 자격인지 선정 후 수행할 업무인지 확인이 필요합니다.',
  }
  const label = item.label && item.label !== '참여 자격' ? item.label : '신청 조건'
  return {
    title: label + '의 적용 기준',
    check: label + '이 신청 자격·우대·제외 중 어느 기준에 해당하는지 확인해 주세요.',
    context: label + '에 관한 문구는 원문에서 확인되지만, 신청 자격·우대·제외 기준과 연결되는 문맥이 확인되지 않았습니다. 해당 문구의 앞뒤 안내를 함께 확인해 주세요.',
  }
}

export function explainParticipationReview(item: ParticipationRule) {
  const reason = item.reviewReason ?? legacyReasons[item.text.trim()]
  const subject = topic(item)
  switch (reason) {
    case 'TABLE_MAPPING_UNCLEAR': {
      if (item.label === '참여기관 구성') return {
        title: '기관별 역할과 필수 참여 구성',
        reason: '추출된 표에서 기관별 역할과 조건의 연결을 확인할 수 없습니다. 주관·공동기관의 자격, 필수 참여기관과 예외를 원문 표에서 확인해 주세요.',
      }

      if (/평가 (?:가점|감점)/u.test(item.label)) return {
        title: item.label + '의 항목별 인정 기준',
        reason: '추출된 표에서 조건·점수·증빙의 연결을 확인할 수 없습니다. 원문 표의 각 항목과 공통 적용 기준을 확인해 주세요.',
      }

      const original = item.sources.map(source => source?.excerpt ?? '').join(' ').replace(/\s+/g, '')
      const institutions = /공공/.test(original) && /민간/.test(original)
      return {
        title: institutions ? '기관 유형별 신청 자격' : '대상별 자격 요건',
        reason: institutions
          ? '공공기관·민간기관 구분과 자격 문장의 연결이 명확하지 않습니다. 각 기관에 적용되는 기준과 별도 요건을 원문 표에서 확인해 주세요.'
          : '표의 대상 구분과 자격 문장이 연결되지 않아 대상별 적용 요건을 확정할 수 없습니다. 각 대상에 연결된 기준을 원문 표에서 확인해 주세요.',
      }
    }
    case 'INCOMPLETE_TEXT':
      return { title: subject.title, reason: '조건 문장이 끝까지 확인되지 않아 뒤에 이어지는 기준이나 예외를 확정할 수 없습니다. 원문에서 문장 전체와 다음 항목까지 확인해 주세요.' }
    case 'CONFLICTING_CRITERIA': {
      const variants = [...new Set(item.outcomes.map(outcome => outcome.variant))].join('·')
      return { title: variants ? variants + ' 신청 기준' : '신청 유형별 적용 기준',
        reason: '같은 대상에 서로 다른 신청 유형 기준이 함께 확인됩니다. 각 원문의 적용 대상·연도와 예외 조건을 대조해 주세요.' }
    }
    case 'CLASSIFICATION_UNCLEAR':
      return { title: subject.title, reason: '표에서 이 항목의 필수·우대·제외 구분이 명확하지 않습니다. ' + subject.check }
    case 'SOURCE_CONTEXT_UNCONFIRMED':
      return { title: subject.title, reason: subject.context }
    case 'MIXED_REQUIREMENT':
      return { title: subject.title, reason: '신청 자격과 우대·가점 문구가 한 항목에 섞여 있습니다. 반드시 충족할 부분과 가점만 주는 부분을 구분해 확인해 주세요.' }
    case 'PREFERENCE_NEGATED':
      return { title: subject.title, reason: '우대·가점을 적용하지 않는다는 문구가 함께 있어 우대 대상으로 표시하지 않았습니다. 미적용 대상과 예외 범위를 원문에서 확인해 주세요.' }
    default:
      // Old responses may lack provenance. Do not claim a broken table, missing
      // threshold or conflicting criterion simply because a keyword is present.
      return { title: subject.title, reason: '현재 안내에서 이 항목의 적용 구분은 확인되지 않은 상태입니다. ' + subject.check }
  }
}
